CREATE TABLE `outcome_events` (
	`id` int AUTO_INCREMENT NOT NULL,
	`furnisherId` varchar(36) NOT NULL,
	`eventId` varchar(128) NOT NULL,
	`keyId` varchar(64) NOT NULL,
	`outcome` enum('paid','refunded','delivered','disputed','payment_failed','not_delivered','access_revoked','policy_violation') NOT NULL,
	`subjectRef` json NOT NULL,
	`occurredAt` datetime(3) NOT NULL,
	`relationType` enum('disputes','corrects','supersedes','withdraws'),
	`relationTargetEventId` varchar(128),
	`signedEvent` json NOT NULL,
	`signedEventHash` varchar(64) NOT NULL,
	`packetId` varchar(36) NOT NULL,
	`entryHash` varchar(64) NOT NULL,
	`sequence` bigint,
	`caCreatedAt` datetime(3) NOT NULL,
	`receivedAt` datetime(3) NOT NULL,
	`receipt` json,
	`proofOk` boolean NOT NULL DEFAULT false,
	`proofChecks` json,
	`proofCheckedAt` datetime(3),
	`displayState` enum('unverified','verified','disputed','withdrawn','superseded') NOT NULL DEFAULT 'unverified',
	`dataClass` enum('test','live') NOT NULL,
	CONSTRAINT `outcome_events_id` PRIMARY KEY(`id`),
	CONSTRAINT `outcome_events_packetId_unique` UNIQUE(`packetId`),
	CONSTRAINT `outcome_events_furnisher_event_uq` UNIQUE(`furnisherId`,`eventId`)
);
